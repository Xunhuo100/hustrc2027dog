#!/usr/bin/env python3
"""Build a self-contained MJCF course and robot scenes in wheel_leg_mujoco."""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import xml.etree.ElementTree as ET


WORKSPACE = Path(__file__).resolve().parents[1]


def write_xml(root, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(root)
    ET.ElementTree(root).write(path, encoding='utf-8', xml_declaration=True)


def embed_obj(mesh, source):
    """Keep original triangle order while removing external mesh file dependencies."""
    vertices, faces = [], []
    for line in source.read_text().splitlines():
        values = line.split()
        if not values or values[0].startswith('#'):
            continue
        if values[0] == 'v':
            if len(values) != 4 or not all(math.isfinite(float(v)) for v in values[1:]):
                raise ValueError('Invalid vertex in ' + str(source))
            vertices.extend(values[1:])
        elif values[0] == 'f':
            if len(values) != 4:
                raise ValueError('Only triangle OBJ files are supported: ' + str(source))
            faces.extend(int(v.split('/')[0]) - 1 for v in values[1:])
    if not vertices or not faces or min(faces) < 0 or max(faces) >= len(vertices) // 3:
        raise ValueError('Invalid triangle mesh: ' + str(source))
    mesh.attrib.pop('file')
    mesh.set('vertex', ' '.join(vertices))
    mesh.set('face', ' '.join(map(str, faces)))


def build_course(assets, target, metadata):
    root = ET.parse(assets/'course.xml').getroot()
    root.tag = 'mujoco'
    root.set('model', 'complete svproj obstacle course')
    root.insert(0, ET.Comment(
        'Generated by tools/build_workspace_map.py from robot.svproj. '
        'All 28 visual solids and 327 convex collision parts are embedded. '
        'Metres, Z up; mesh files are not required for this map.'))
    for mesh in root.findall('./asset/mesh'):
        relative = Path(mesh.get('file'))
        if relative.parts[0] == 'svproj_course':
            relative = Path(*relative.parts[1:])
        path = (assets/relative).resolve()
        if not path.is_relative_to(assets.resolve()):
            raise ValueError('Mesh path escapes asset directory')
        embed_obj(mesh, path)
    world = root.find('worldbody')
    for geom in world.findall('geom'):
        if geom.get('name', '').startswith('svproj_collision_'):
            geom.set('contype', '1')
            geom.set('conaffinity', '1')
    ET.SubElement(world, 'geom', name='svproj_ground', type='plane', pos='0 0 0',
                  size='16 10 .1', group='0', contype='1', conaffinity='1',
                  rgba='.18 .22 .24 1', friction='.8 .02 .001', condim='3')
    ET.SubElement(world, 'light', name='svproj_light', pos='5 -1.5 12', dir='0 0 -1',
                  directional='true', diffuse='.8 .8 .8', ambient='.35 .35 .35')
    ET.SubElement(world, 'camera', name='svproj_overview', pos='5 -10 9',
                  xyaxes='1 0 0 0 .70710678 .70710678', fovy='55')
    ET.SubElement(world, 'camera', name='svproj_top', pos='5 -1.5 13',
                  quat='1 0 0 0', fovy='55')
    ET.SubElement(root, 'statistic', center='5 -1.5 .3', extent='8')
    visual = ET.SubElement(root, 'visual')
    ET.SubElement(visual, 'headlight', diffuse='.5 .5 .5', ambient='.3 .3 .3', specular='0 0 0')
    ET.SubElement(visual, 'global', azimuth='90', elevation='-65', offwidth='1400', offheight='900')
    custom = ET.SubElement(root, 'custom')
    for name, key in [('svproj_spawn', 'spawn'), ('svproj_grid_origin', 'grid_origin'),
                      ('svproj_tile_size', 'tile_size')]:
        ET.SubElement(custom, 'numeric', name=name, data=' '.join(map(str, metadata[key])))
    write_xml(root, target)


def asset_directory(model_file, declared, fallback):
    declared_path = model_file.parent/declared
    if declared_path.is_dir():
        return declared_path.resolve()
    if fallback.is_dir():
        return fallback.resolve()
    raise FileNotFoundError('Missing asset directory for ' + str(model_file))


def build_robot_scene(source, target, course, metadata):
    root = ET.parse(source).getroot()
    root.set('model', source.stem + ' on complete svproj course')
    root.insert(0, ET.Comment(
        'Generated from ' + source.name + ' by tools/build_workspace_map.py. '
        'Robot parameters are preserved; asset paths, spawn and environment are composed here.'))
    compiler = root.find('compiler')
    for attribute in ['meshdir', 'texturedir']:
        if compiler.get(attribute):
            directory = asset_directory(source, compiler.get(attribute), source.parent.parent/'assets')
            compiler.set(attribute, os.path.relpath(directory, target.parent))
    # The course owns the only ground plane and its lighting.
    world = root.find('worldbody')
    for element in list(world):
        if element.tag == 'light' or (element.tag == 'geom' and element.get('type') == 'plane'):
            world.remove(element)
    bases = [body for body in world.findall('body')
             if body.find('freejoint') is not None
             or any(j.get('type') == 'free' for j in body.findall('joint'))]
    if len(bases) != 1:
        raise ValueError('Expected one floating robot base in ' + str(source))
    base = bases[0]
    position = [float(v) for v in base.get('pos', '0 0 0').split()]
    home = root.find("./keyframe/key[@name='home']")
    if home is not None:
        position[2] = float(home.get('qpos').split()[2])
    position[:2] = metadata['spawn'][:2]
    base.set('pos', ' '.join(map(str, position)))
    for key in root.findall('./keyframe/key'):
        if key.get('qpos'):
            qpos = key.get('qpos').split()
            qpos[:2] = list(map(str, metadata['spawn'][:2]))
            key.set('qpos', ' '.join(qpos))
    ET.SubElement(root, 'include', file=os.path.relpath(course, target.parent))
    write_xml(root, target)


def build(assets, models, source):
    metadata = json.loads((assets/'manifest.json').read_text())
    if hashlib.sha256(source.read_bytes()).hexdigest() != metadata['input_sha256']:
        raise ValueError('Converted course does not match the supplied robot.svproj')
    course = models/'terrains/svproj_course.xml'
    build_course(assets, course, metadata)
    destinations = {}
    for robot, filename in [('go2w', 'go2w.xml'), ('hustdog_v11', 'hustdog_v11.xml')]:
        directory = models/robot/'urdf'
        target = directory/'scene_svproj.xml'
        build_robot_scene(directory/filename, target, course, metadata)
        destinations[robot] = str(target)
    manifest = dict(metadata)
    manifest['mjcf_meshes_embedded'] = True
    manifest['workspace_scenes'] = {name:os.path.relpath(path, models) for name, path in destinations.items()}
    (course.parent/'svproj_course.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({'self_contained_map':str(course), 'scenes':destinations,
                      'map_bytes':course.stat().st_size}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', type=Path, default=WORKSPACE/'assets/svproj_course')
    parser.add_argument('--models', type=Path, default=WORKSPACE/'src/wheel_leg_mujoco/models')
    parser.add_argument('--source', type=Path, default=WORKSPACE/'robot.svproj')
    args = parser.parse_args()
    build(args.assets.resolve(), args.models.resolve(), args.source.resolve())
